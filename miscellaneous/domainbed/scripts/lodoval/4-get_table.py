import argparse
from pathlib import Path
import numpy as np
import pandas as pd

# In this framework the algorithm is always the same (the CSV has no
# "algorithm" column), so it is added in load().
ALGORITHM = "SIMPLE"

METRICS = {
    "test_acc": "Acc",
    "test_bacc": "BAcc",
    "test_f1": "F1",
    "test_auroc": "AUROC",
    "test_sens": "Sens",
    "test_spec": "Spec",
}
KEYS = ["dataset", "algorithm"]


def load(csv):
    df = pd.read_csv(csv)

    # The CSV does not include "algorithm": it is always SIMPLE.
    if "algorithm" not in df.columns:
        df["algorithm"] = ALGORITHM
    else:
        df["algorithm"] = df["algorithm"].fillna(ALGORITHM)

    sens = [c for c in df if c.startswith("test_sensitivity_c")]
    spec = [c for c in df if c.startswith("test_specificity_c")]
    if "test_sensitivity_c2" in df:
        is_multi = df["test_sensitivity_c2"].notna()
    else:
        is_multi = pd.Series(False, index=df.index)
    # Binary: class 1 = cancer. Multiclass: mean over the classes.
    df["test_sens"] = np.where(is_multi, df[sens].mean(axis=1), df["test_sensitivity_c1"])
    df["test_spec"] = np.where(is_multi, df[spec].mean(axis=1), df["test_specificity_c1"])
    return df

def aggregate(df, agg):
    metrics = list(METRICS)

    n_env = df.groupby(KEYS + ["trial_seed"])["test_env"].nunique()
    if n_env.nunique() > 1:
        print("WARNING: some seeds have a different number of domains.")

    # 1) mean over domains within each seed
    per_seed = df.groupby(KEYS + ["trial_seed"])[metrics].mean()

    # 2) aggregation across seeds
    g = per_seed.groupby(KEYS)
    center = g.mean() if agg == "mean" else g.median()
    se = g.std(ddof=1) / np.sqrt(g.count())
    n_seeds = int(g.size().min())
    return center, se, n_seeds


def esc(s):
    return str(s).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def fmt(v, s, scale, dec, bold):
    val = f"{v * scale:.{dec}f}"
    if bold:
        val = rf"\mathbf{{{val}}}"
    if np.isnan(s):
        return f"${val}$"
    return f"${val} \\pm {s * scale:.{dec}f}$"


def to_latex(center, se, agg, n_seeds, scale, dec, caption, label):
    best = center.eq(center.groupby(level="dataset").transform("max"))
    cols = list(METRICS)

    if caption is None:
        what = "Mean" if agg == "mean" else "Median"
        caption = (
            f"{what} $\\pm$ standard error over {n_seeds} seeds, "
            "averaged over test domains. Best result per dataset in bold."
        )

    lines = [
        r"% Required packages: \usepackage{booktabs}  \usepackage{multirow}",
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        r"\begin{tabular}{ll" + "c" * len(cols) + "}",
        r"\toprule",
        "Dataset & Method & " + " & ".join(METRICS.values()) + r" \\",
        r"\midrule",
    ]

    datasets = center.index.get_level_values("dataset").unique()
    for i, ds in enumerate(datasets):
        algs = center.loc[ds].index
        for j, alg in enumerate(algs):
            ds_cell = rf"\multirow{{{len(algs)}}}{{*}}{{{esc(ds)}}}" if j == 0 else ""
            cells = [
                fmt(center.loc[(ds, alg), m], se.loc[(ds, alg), m],
                    scale, dec, best.loc[(ds, alg), m])
                for m in cols
            ]
            lines.append(" & ".join([ds_cell, esc(alg)] + cells) + r" \\")
        if i < len(datasets) - 1:
            lines.append(r"\midrule")

    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--csv", required=True, help="CSV generated by the previous script")
    p.add_argument("--agg", choices=["mean", "median"], default="mean")
    p.add_argument("--scale", type=float, default=100, help="100 = percentage")
    p.add_argument("--decimals", type=int, default=2)
    p.add_argument("--caption", default=None)
    p.add_argument("--label", default="tab:results")
    p.add_argument("--out", default=None, help="Output .tex file")
    args = p.parse_args()

    df = load(args.csv)
    center, se, n_seeds = aggregate(df, args.agg)
    tex = to_latex(center, se, args.agg, n_seeds, args.scale,
                   args.decimals, args.caption, args.label)

    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(tex + "\n", encoding="utf-8")
        print(f"Table saved to {args.out}")
    else:
        print(tex)


if __name__ == "__main__":
    main()